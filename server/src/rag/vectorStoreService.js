const { chroma } = require("../config/chroma");

const {
  EMBEDDING_DIMENSIONS,
  generateBatchEmbeddings,
  generateQueryEmbedding,
  prepareDocumentText,
} = require("../services/embeddingService");

const COLLECTION_NAME = "vortes_code_embeddings";

const COLLECTION_METADATA = {
  description: "Code embeddings for Vortes repository RAG",
  embedding_model: "gemini-embedding-2",
  embedding_dimensions: EMBEDDING_DIMENSIONS,
  "hnsw:space": "cosine",
};

const withTimeout = (promise, ms, errorMsg) => {
  let timeoutId;
  const timeoutPromise = new Promise((_, reject) => {
    timeoutId = setTimeout(() => reject(new Error(errorMsg)), ms);
  });
  return Promise.race([promise, timeoutPromise]).finally(() =>
    clearTimeout(timeoutId),
  );
};

const getCollection = async () => {
  try {
    const collection = await withTimeout(
      chroma.getOrCreateCollection({
        name: COLLECTION_NAME,
        metadata: COLLECTION_METADATA,
        embeddingFunction: null,
      }),
      2500,
      "ChromaDB connection timed out (is Chroma running?)",
    );

    return collection;
  } catch (error) {
    throw new Error(`Failed to get ChromaDB collection: ${error.message}`, {
      cause: error,
    });
  }
};

const prepareChunksForStorage = (repositoryId, chunks) => {
    if (!Array.isArray(chunks) || chunks.length === 0) {
        throw new Error("No chunks provided for insertion.");
    }

    const ids = [];
    const documents = [];
    const metadatas = [];
    const uniqueIds = new Set();

    chunks.forEach((chunk, index) => {
        const metadata = chunk.metadata || {};

        if (!chunk.content || !chunk.content.trim()) {
            throw new Error(`Invalid chunk content at index ${index}.`);
        }

        const chunkRepositoryId = String(
            metadata.repositoryId || repositoryId
        );

        if (chunkRepositoryId !== String(repositoryId)) {
            throw new Error(`Repository ID mismatch at index ${index}.`);
        }

        const filePath = metadata.filePath || chunk.filePath;

        if (!filePath) {
            throw new Error(`Missing file path at index ${index}.`);
        }

        const id =
            chunk.id ||
            `${repositoryId}_${filePath}_${metadata.chunkIndex ?? index}`;

        if (uniqueIds.has(id)) {
            throw new Error(`Duplicate chunk ID: ${id}`);
        }

        uniqueIds.add(id);
        ids.push(id);

        documents.push(
            prepareDocumentText(chunk.content, filePath)
        );

        const cleanMetadata = {};

        Object.entries(metadata).forEach(([key, value]) => {
            if (
                value !== undefined &&
                value !== null &&
                ["string", "number", "boolean"].includes(typeof value) &&
                !(typeof value === "number" && !Number.isFinite(value))
            ) {
                cleanMetadata[key] = value;
            }
        });

        cleanMetadata.repositoryId = chunkRepositoryId;

        metadatas.push(cleanMetadata);
    });

    return {
        ids,
        documents,
        metadatas,
    };
};

const addDocuments = async (repositoryId, chunks) => {
    try {
        if (!Array.isArray(chunks) || chunks.length === 0) {
            throw new Error("No chunks provided for insertion.");
        }

        const collection = await getCollection();

        const ids = [];
        const documents = [];
        const metadatas = [];

        // Prepare chunks and preserve their original IDs and metadata
        chunks.forEach((chunk, index) => {
            const metadata = chunk.metadata || {};

            if (!chunk.content || !chunk.content.trim()) {
                throw new Error(`Invalid chunk content at index ${index}.`);
            }

            const chunkRepositoryId = String(
                metadata.repositoryId || repositoryId
            );

            if (chunkRepositoryId !== String(repositoryId)) {
                throw new Error(
                    `Repository ID mismatch in chunk ${index}.`
                );
            }

            const filePath = metadata.filePath || chunk.filePath;

            if (!filePath) {
                throw new Error(
                    `Missing file path in chunk ${index}.`
                );
            }

            // Preserve the ID generated by codeChunker.js
            const id =
                chunk.id ||
                `${repositoryId}_${filePath}_${metadata.chunkIndex ?? index}`;

            if (ids.includes(id)) {
                throw new Error(`Duplicate chunk ID: ${id}`);
            }

            ids.push(id);

            // Format content for Gemini embedding
            documents.push(
                prepareDocumentText(chunk.content, filePath)
            );

            // ChromaDB metadata must contain scalar values
            const cleanMetadata = {};

            Object.entries(metadata).forEach(([key, value]) => {
                if (
                    value !== undefined &&
                    value !== null &&
                    ["string", "number", "boolean"].includes(typeof value) &&
                    !(typeof value === "number" && !Number.isFinite(value))
                ) {
                    cleanMetadata[key] = value;
                }
            });

            // Ensure repository ID is always available for filtering
            cleanMetadata.repositoryId = chunkRepositoryId;

            metadatas.push(cleanMetadata);
        });

        console.log(`Preparing ${chunks.length} chunks for embedding...`);

        // Generate embeddings in batches
        const embeddings = await generateBatchEmbeddings(documents);

        if (embeddings.length !== chunks.length) {
            throw new Error("Embedding count does not match chunk count.");
        }

        // Insert documents, embeddings and complete metadata
        await collection.upsert({
            ids,
            documents,
            embeddings,
            metadatas,
        });

        console.log(
            `Successfully stored ${chunks.length} chunks in ChromaDB.`
        );

        return {
            success: true,
            count: chunks.length,
        };

    } catch (error) {
        console.error("Failed to add documents:", error.message);
        throw error;
    }
};

const replaceRepositoryDocuments = async (repositoryId, chunks) => {
    try {
        const collection = await getCollection();

        // 1. Prepare new chunks
        const {
            ids,
            documents,
            metadatas,
        } = prepareChunksForStorage(repositoryId, chunks);

        console.log("Generating embeddings for new repository version...");

        // 2. Generate all embeddings BEFORE modifying existing vectors
        const embeddings = await generateBatchEmbeddings(documents);

        if (embeddings.length !== ids.length) {
            throw new Error("Embedding count mismatch.");
        }

        // 3. Retrieve existing repository chunk IDs
        console.log("Retrieving existing repository vectors...");

        const existing = await collection.get({
            where: {
                repositoryId: String(repositoryId),
            },
            include: ["metadatas"],
        });

        const existingIds = existing.ids || [];

        // 4. Insert/update new vectors
        console.log("Inserting new repository vectors...");

        await collection.upsert({
            ids,
            documents,
            embeddings,
            metadatas,
        });

        // 5. Identify outdated chunks
        const newIdSet = new Set(ids);

        const staleIds = existingIds.filter(
            (id) => !newIdSet.has(id)
        );

        // 6. Delete outdated chunks only after successful upsert
        if (staleIds.length > 0) {
            console.log(`Removing ${staleIds.length} outdated chunks...`);

            await collection.delete({
                ids: staleIds,
            });
        }

        console.log("Repository re-indexing completed successfully!");

        return {
            success: true,
            count: ids.length,
            updatedOrInserted: ids.length,
            deleted: staleIds.length,
        };

    } catch (error) {
        console.error("Repository re-indexing failed:", error.message);
        throw error;
    }
};

const searchSimilar = async (query, repositoryId, limit = 5) => {
  try {
    // Validate query
    if (typeof query !== "string" || !query.trim()) {
      throw new Error("Search query must be a non-empty string");
    }

    // Validate repository ID
    if (!repositoryId) {
      throw new Error("Repository ID is required");
    }

    // Validate result limit
    if (!Number.isInteger(limit) || limit < 1) {
      throw new Error("Limit must be a positive integer");
    }

    // Get ChromaDB collection
    const collection = await getCollection();

    // Generate query embedding
    const queryEmbedding = await generateQueryEmbedding(query);

    // Validate embedding dimensions
    if (queryEmbedding.length !== EMBEDDING_DIMENSIONS) {
      throw new Error("Invalid query embedding dimensions");
    }

    // Search ChromaDB
    const results = await collection.query({
      queryEmbeddings: [queryEmbedding],
      nResults: limit,

      // Search only within the requested repository
      where: {
        repositoryId: String(repositoryId),
      },
    });

    // Format search results
    const formattedResults = (results.ids?.[0] || []).map((id, index) => ({
      id,
      content: results.documents?.[0]?.[index] || "",
      metadata: results.metadatas?.[0]?.[index] || {},
      distance: results.distances?.[0]?.[index] ?? null,
    }));

    return formattedResults;
  } catch (error) {
    throw new Error(`Similarity search failed: ${error.message}`, {
      cause: error,
    });
  }
};

const deleteDocuments = async (documentIds) => {
  try {
    if (!Array.isArray(documentIds) || documentIds.length === 0) {
      throw new Error("Document IDs must be a non-empty array");
    }

    if (documentIds.some((id) => typeof id !== "string" || !id.trim())) {
      throw new Error("Every document ID must be a non-empty string");
    }

    const uniqueIds = [...new Set(documentIds)];

    const collection = await getCollection();

    await collection.delete({
      ids: uniqueIds,
    });

    return {
      success: true,
      deletedCount: uniqueIds.length,
    };
  } catch (error) {
    throw new Error(`Failed to delete documents: ${error.message}`, {
      cause: error,
    });
  }
};

const deleteRepository = async (repositoryId) => {
  try {
    if (typeof repositoryId !== "string" || !repositoryId.trim()) {
      throw new Error("A valid repository ID is required");
    }

    const collection = await getCollection();

    // Find repository documents before deletion
    const existingDocuments = await collection.get({
      where: {
        repositoryId: repositoryId.trim(),
      },
    });

    const documentCount = existingDocuments.ids.length;

    if (documentCount === 0) {
      return {
        success: true,
        repositoryId,
        deletedCount: 0,
        message: "No documents found for this repository",
      };
    }

    // Delete all documents belonging to this repository
    await collection.delete({
      where: {
        repositoryId: repositoryId.trim(),
      },
    });

    return {
      success: true,
      repositoryId,
      deletedCount: documentCount,
    };
  } catch (error) {
    throw new Error(
      `Failed to delete repository embeddings: ${error.message}`,
      { cause: error },
    );
  }
};

const getCollectionCount = async (repositoryId = null) => {
  try {
    const collection = await getCollection();

    // Return total collection count
    if (repositoryId === null) {
      return await collection.count();
    }

    if (typeof repositoryId !== "string" || !repositoryId.trim()) {
      throw new Error("Invalid repository ID");
    }

    // Get documents belonging to a specific repository
    const results = await collection.get({
      where: {
        repositoryId: repositoryId.trim(),
      },
    });

    return results.ids.length;
  } catch (error) {
    throw new Error(`Failed to get collection count: ${error.message}`, {
      cause: error,
    });
  }
};

module.exports = {
  getCollection,
  addDocuments,
  searchSimilar,
  deleteDocuments,
  deleteRepository,
  getCollectionCount,
  replaceRepositoryDocuments,
  COLLECTION_NAME,
  COLLECTION_METADATA,
};
